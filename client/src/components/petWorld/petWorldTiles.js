export function getBiomeUi(biome) {
  return BIOME_UI[biome] || BIOME_UI.grasslands;
}

export function getTilePalette(biome, tileType) {
  const b = getBiomeUi(biome);
  if (tileType === 'water') return { fill: b.water, detail: b.waterHighlight, deep: b.waterDeep, shore: b.waterShore };
  if (tileType === 'tree') return { fill: b.tree, detail: b.treeHighlight, trunk: b.treeTrunk };
  if (tileType === 'rock') return { fill: b.rock, detail: b.rockHighlight };
  if (tileType === 'bush') return { fill: b.bush, detail: b.bushDetail };
  const grounds = b.ground;
  const hash = String(tileType || '').split('').reduce((sum, ch) => sum + ch.charCodeAt(0), 0);
  return { fill: grounds[hash % grounds.length], detail: b.groundDetail };
}
